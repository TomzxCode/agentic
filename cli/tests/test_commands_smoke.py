"""A smoke pass over every command group in text mode."""

from agentic_cli.commands import harnesses, health, items, links, repositories, runs, settings, tags, tasks


def test_commands_emit_text(text_format, fake_client):
    assert "ok (agentic)" in health.health()
    assert "t1" in tasks.task_list()
    assert "bug" in tags.tag_list()
    assert "T" in tasks.task_get("t1")
    assert "requested by: Ada" in tasks.task_get("t1")
    assert "created t2" in tasks.task_create(title="New")
    assert "updated t1" in tasks.task_update("t1", title="T")
    assert "deleted t1" in tasks.task_delete("t1")
    assert "created" in tasks.task_timeline("t1")
    assert "linked i1 to t1" in links.link_add("t1", item_id="i1")
    assert "linked i1 to t1" in links.link_add("t1", url="u")
    assert "unlinked i1" in links.link_remove("t1", "i1")
    assert "i1" in items.item_list()
    assert "N" in items.item_get("i1")
    assert "created i2" in items.item_create(content="x")
    assert "refreshed i1" in items.item_refresh("i1")
    assert "deleted i1" in items.item_delete("i1")
    assert "r1" in repositories.repository_list()
    assert "added r2" in repositories.repository_add("/p")
    assert "removed r1" in repositories.repository_remove("r1")
    assert "w1" in repositories.worktree_list("t1")
    assert "created worktree w2" in repositories.worktree_create("t1")
    assert "removed worktree w1" in repositories.worktree_remove("t1", "w1")
    assert "r1" in runs.run_list("t1")
    assert "session: s" in runs.run_get("r1")
    assert "[message] hi" in runs.run_events("r1")
    assert "started run r3" in runs.run_create("t1", "p")
    assert "cancelling r1" in runs.run_cancel("r1")
    assert "- [x] a" in runs.context_get("t1")
    assert "context refresh started" in runs.context_refresh("t1")
    assert "opencode" in harnesses.harness_list()
    assert "created harness h1" in harnesses.harness_create(name="n", command="c")
    assert "updated harness h1" in harnesses.harness_update("h1", name="n")
    assert "deleted h1" in harnesses.harness_delete("h1")
    assert "openchamber_url" in settings.settings_get()
    assert "openchamber_url" in settings.settings_set(openchamber_url="x")
